/**
 * 마크다운 본문을 컴팩트한 한 줄 라벨(문항 네비게이터 등)에 안전하게 노출하기 위한 평문 변환.
 *
 * 문항 목록·네비게이터는 본문을 MarkdownText로 렌더할 수 없는 좁은 공간이라, 원시 마크다운
 * 문법(표 파이프·`:---` 구분선·강조 기호 등)이 그대로 새어 나온다(SC-001 위반). 여기서 표·수식·
 * 코드 등 구조 요소는 제거하고 사람이 읽는 텍스트만 남겨, 라벨에 원시 문법이 노출되지 않게 한다.
 */
export const toPlainText = (markdown: string): string =>
  markdown
    .replace(/```[\s\S]*?```/g, ' ') // 코드 펜스 블록
    .replace(/`([^`]+)`/g, '$1') // 인라인 코드
    .replace(/\$\$[\s\S]*?\$\$/g, ' ') // 블록 수식
    .replace(/\$([^$]+)\$/g, '$1') // 인라인 수식
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ') // 이미지
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1') // 링크 → 텍스트만
    .replace(/^\s*\|.*\|\s*$/gm, ' ') // 표 행(파이프로 감싼 줄)
    .replace(/^\s*:?-{3,}:?\s*$/gm, ' ') // 구분선/hr
    .replace(/^\s{0,3}#{1,6}\s+/gm, '') // 제목 마커
    .replace(/^\s{0,3}>\s?/gm, '') // 인용 마커
    .replace(/[*_~`]/g, '') // 강조·취소선 기호
    .replace(/\s+/g, ' ') // 공백 정리
    .trim();
